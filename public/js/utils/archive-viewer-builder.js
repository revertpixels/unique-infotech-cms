  function resolveMediaUrl(relPath) {
    if (!relPath) return Promise.resolve('');
    if (!unlockKey) return Promise.resolve(relPath);
    if (mediaUrlCache[relPath]) return Promise.resolve(mediaUrlCache[relPath]);
    if (pendingMedia[relPath]) return pendingMedia[relPath];

    var p = new Promise(function(resolve){
      function decryptPayload(rec) {
        if (!rec) { resolve(''); return; }
        var iv = b64ToBytes(rec.ivB64);
        var ct = b64ToBytes(rec.dataB64);
        var aad = new TextEncoder().encode(relPath);
        crypto.subtle.decrypt({ name: 'AES-GCM', iv: iv, additionalData: aad }, unlockKey, ct).then(function(buf){
          var blob = new Blob([buf], { type: rec.mime || 'application/octet-stream' });
          var url = URL.createObjectURL(blob);
          mediaBlobCache[relPath] = blob;
          mediaUrlCache[relPath] = url;
          resolve(url);
        }).catch(function(){ resolve(''); });
      }
      if (registeredEncMedia[relPath]) { decryptPayload(registeredEncMedia[relPath]); return; }
      var s = document.createElement('script');
      s.src = relPath + '.enc.js';
      s.onload = function(){ decryptPayload(registeredEncMedia[relPath]); };
      s.onerror = function(){ resolve(''); };
      document.head.appendChild(s);
    });
    pendingMedia[relPath] = p;
    return p;
  }

