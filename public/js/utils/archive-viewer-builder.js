  function openPaymentReceiptView(entry, backPage) {
    if (!entry) return;
    var s = findStudent(entry.studentDocId);
    if (!s) return;
    var pt = String(entry.type || '').toUpperCase().trim();
    if (entry.isAdmissionGroup || pt === 'AD' || pt === 'FULL' || pt === 'MAT') {
      openAdmissionReceiptView(s.id, backPage);
      return;
    }
    NAV.receiptBackPage = backPage || (NAV.page === 'student-profile' ? 'student-profile' : 'payments');
    NAV.studentDocId = s.id;
    NAV.receiptMode = 'payment';
    NAV.receiptEntry = entry;
    NAV.page = 'payment-receipt';
    renderView();
    window.scrollTo(0, 0);
  }

  async function waitFontsAndImages(scopeEl) {
    if (document.fonts && document.fonts.ready) {
      try { await document.fonts.ready; } catch (_) {}
    }
    var imgs = scopeEl ? Array.prototype.slice.call(scopeEl.querySelectorAll('img')) : [];
    await Promise.all(imgs.map(function(im){
      if (im.complete) return Promise.resolve();
      return new Promise(function(res){
        im.addEventListener('load', res, { once: true });
        im.addEventListener('error', res, { once: true });
        setTimeout(res, 2000);
      });
    }));
  }

  async function triggerPrintHtml(htmlContent) {
    if (!PRINT_STAGE) { window.print(); return; }
    PRINT_STAGE.innerHTML = htmlContent;
    await hydrateImages(PRINT_STAGE);
    paintIcons(PRINT_STAGE);
    await waitFontsAndImages(PRINT_STAGE);
    document.body.classList.add('av-printing');
    var cleanup = function(){
      document.body.classList.remove('av-printing');
      PRINT_STAGE.innerHTML = '';
      window.removeEventListener('afterprint', cleanup);
    };
    window.addEventListener('afterprint', cleanup);
    setTimeout(function(){
      window.print();
      setTimeout(cleanup, 1200);
    }, 60);
  }

